// genmodels erzeugt models_gen.go aus der Modellliste von aioshelly
// (Home Assistant, Apache-2.0). Aufruf: go generate ./...
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"regexp"
	"sort"
	"strconv"
)

const src = "https://raw.githubusercontent.com/home-assistant-libs/aioshelly/main/aioshelly/const.py"

var (
	reConst  = regexp.MustCompile(`(?m)^(MODEL_\w+)\s*=\s*"([^"]+)"`)
	reDevice = regexp.MustCompile(`(?s)ShellyDevice\(\s*model=(MODEL_\w+),\s*name="([^"]+)",.*?gen=GEN(\d)`)
)

func main() {
	out := "models_gen.go"
	if len(os.Args) > 1 {
		out = os.Args[1]
	}
	resp, err := http.Get(src)
	if err != nil {
		fail(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		fail(fmt.Errorf("%s: %s", src, resp.Status))
	}
	body, err := io.ReadAll(resp.Body)
	if err != nil {
		fail(err)
	}

	codes := map[string]string{}
	for _, m := range reConst.FindAllSubmatch(body, -1) {
		codes[string(m[1])] = string(m[2])
	}
	type entry struct {
		code, name string
		gen        int
	}
	var entries []entry
	seen := map[string]bool{}
	for _, m := range reDevice.FindAllSubmatch(body, -1) {
		code, ok := codes[string(m[1])]
		if !ok || seen[code] {
			continue
		}
		seen[code] = true
		gen, _ := strconv.Atoi(string(m[3]))
		entries = append(entries, entry{code, string(m[2]), gen})
	}
	if len(entries) < 50 {
		fail(fmt.Errorf("nur %d Modelle gefunden - hat sich das Format von const.py geändert?", len(entries)))
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].code < entries[j].code })

	var b bytes.Buffer
	b.WriteString("// Code generated by tools/genmodels; DO NOT EDIT.\n")
	b.WriteString("// Quelle: " + src + " (Apache-2.0)\n\n")
	b.WriteString("package main\n\nvar knownModels = map[string]modelInfo{\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "\t%q: {%q, %d},\n", e.code, e.name, e.gen)
	}
	b.WriteString("}\n")
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(out, formatted, 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("%s: %d Modelle\n", out, len(entries))
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "genmodels:", err)
	os.Exit(1)
}
